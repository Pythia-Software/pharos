//go:build darwin

package credentialstore

import "golang.org/x/sys/unix"

// Foundation's isExcludedFromBackup resource value writes this binary-plist
// marker. Set it on the open directory and on each new inode before publishing
// so Time Machine does not copy live installation credentials.
var backupExclusion = []byte{0x62, 0x70, 0x6c, 0x69, 0x73, 0x74, 0x30, 0x30, 0x5f, 0x10, 0x11, 0x63, 0x6f, 0x6d, 0x2e, 0x61, 0x70, 0x70, 0x6c, 0x65, 0x2e, 0x62, 0x61, 0x63, 0x6b, 0x75, 0x70, 0x64, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x1c}

func excludeBackup(fd int) error {
	if err := unix.Fsetxattr(fd, "com.apple.metadata:com_apple_backup_excludeItem", backupExclusion, 0); err != nil {
		return ErrUnsafe
	}
	return nil
}
